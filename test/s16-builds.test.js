test('the three provisional Season 16 builds score without soul stacks', () => {
  const file = read('../data/s16-builds.json');
  assert.equal(file.season, 16);
  assert.equal(file.provisional, true);
  assert.equal(file.souls, 0);
  assert.equal(file.builds.length, 3);
  const swing = file.builds.find(build => build.id === 's16-double-swing');
  assert.equal(swing.placeholder.status, 'waiting');
  assert.deepEqual(swing.unresolved, []);
  assert.equal(swing.sixthSkill.confirmed, false);
  assert.equal(swing.sixthSkill.name, 'Lunging Strike');
  const flay = file.builds.find(build => build.id === 's16-flay');
  assert.ok(flay.sources.includes('https://d4guides.gg/en/build/barbarian-flay'));
  assert.ok(flay.sources.includes('https://d4guides.gg/en/database/horadric-affixes/bloodletters-flow'));
  assert.ok(swing.sources[0].startsWith('https://'));
  const catalog = read('../data/barbarian.json');
  const saved = read('../data/builds.json');
  const build = saved.builds.find(entry => entry.id === 'users-current-build');
  const scores = scoreS16(catalog, build);
  assert.equal(scores.length, 3);
  const byId = Object.fromEntries(scores.map(row => [row.id, row]));
  assert.equal(byId['s16-double-swing'].rank, 41);
  assert.equal(byId['s16-double-swing'].rankMultiplier, 5.4);
  assert.equal(byId['s16-double-swing'].storedCoeff, 114);
  assert.ok(Math.abs(byId['s16-double-swing'].ptrCoeff - 1620) < 1e-6);
  assert.equal(byId['s16-double-swing'].previousCoeff, 150);
  assert.equal(byId['s16-whirlwind'].storedCoeff, 386);
  assert.ok(Math.abs(byId['s16-whirlwind'].ptrCoeff - 386.1) < 1e-6);
  assert.equal(byId['s16-whirlwind'].previousCoeff, 165);
  assert.ok(Math.abs(byId['s16-flay'].ptrCoeff - 1117.8) < 1e-6);
  assert.equal(byId['s16-flay'].previousCoeff, 115);
  assert.equal(byId['s16-flay'].dot, true);
  for (const row of scores) {
    assert.ok(row.max.peak > row.min.peak);
    assert.equal(row.fury, 826);
  }
  const sescheron = byId['s16-whirlwind'].isolation.find(line => /Colossal/.test(line.name));
  assert.ok(Math.abs(sescheron.peak - 7) < 1e-9);
  const streak = byId['s16-double-swing'].isolation.find(line => /5s/.test(line.name));
  assert.ok(Math.abs(streak.peak - 1) < 1e-9);
  assert.ok(streak.average > 2);
  const bleed = byId['s16-flay'].isolation.find(line => /Bleeding/.test(line.name));
  assert.ok(Math.abs(bleed.peak - 3) < 1e-9);
  const ww = byId['s16-whirlwind'];
  assert.equal(ww.attackSpeedModel, 'breakpoints');
  assert.equal(ww.whirlwind.frames, 13);
  assert.equal(ww.furyReport.attackSpeedChangesDamage, true);
  assert.equal(ww.furyReport.holdsFor60, true);
  assert.ok(Math.abs(ww.furyReport.costPerSecond - 30) < 1e-9);
  assert.ok(Math.abs(ww.dps.max.peak - ww.max.peak * (60 / 13)) < 1);
  assert.ok(Math.abs(ww.flatDps.max.peak - ww.max.peak * (30 / 13)) < 1);
  const flat = scoreS16(catalog, build, { whirlwindAttackSpeedModel: 'flat', attackSpeedPct: 120 }).find(row => row.id === 's16-whirlwind');
  assert.equal(flat.attackSpeedModel, 'flat');
  assert.ok(Math.abs(flat.dps.max.peak - ww.flatDps.max.peak) < 1);
  const slower = scoreS16(catalog, build, { attackSpeedPct: 0 }).find(row => row.id === 's16-whirlwind');
  assert.equal(slower.whirlwind.frames, 26);
  assert.ok(Math.abs(slower.dps.max.peak - ww.dps.max.peak / 2) < 1);
  const ds = byId['s16-double-swing'];
  assert.equal(ds.furyReport.sustainable, false);
  assert.ok(ds.furyReport.spenderUptime < 1);
  assert.ok(Math.abs(ds.dps.max.peak - ds.max.peak * ds.attackSpeed.aps) < 1);
  const flayScore = byId['s16-flay'];
  assert.ok(Math.abs(flayScore.dps.max.peak - flayScore.max.peak / 9) < 1);
  const fistsOff = scoreS16(catalog, build, { fistsOfFate: false }).find(row => row.id === 's16-double-swing');
  assert.ok(fistsOff.max.peak < byId['s16-double-swing'].max.peak);
  assert.ok(Math.abs(byId['s16-double-swing'].max.peak / fistsOff.max.peak - 1.505) < 1e-6);
  const doc = readFileSync(new URL('../docs/s16-builds.md', import.meta.url), 'utf8');
  assert.match(doc, /provisional/);
  assert.match(doc, /One-Handed Mace Expertise/);
  assert.match(doc, /5\.40/);
  assert.match(doc, /placeholder/);
  assert.match(doc, /2,426\.80B|Soul Splinter|souls are 0|no soul/i);
  assert.match(doc, /bleed/);
  assert.match(doc, /DPS|damage per second/);
  assert.match(doc, /community-measured S15 \(3\.2\), recheck after S16 launch/);
  assert.match(doc, /91%/);
});

test('Whirlwind frames step at the measured 2H breakpoints', () => {
  assert.equal(whirlwindFrames(0).frames, 26);
  assert.equal(whirlwindFrames(27.4).frames, 26);
  assert.equal(whirlwindFrames(27.5).frames, 20);
  assert.equal(whirlwindFrames(48.8).frames, 17);
  assert.equal(whirlwindFrames(90).frames, 17);
  assert.equal(whirlwindFrames(91).frames, 13);
  assert.equal(whirlwindFrames(120).frames, 13);
  assert.equal(whirlwindFrames(143.5).frames, 10);
  assert.equal(whirlwindFrames(200).frames, 10);
  assert.equal(whirlwindFrames(0, '2h-sword').frames, 24);
  assert.equal(whirlwindFrames(0, '1h').frames, 21);
  const sword = whirlwindFrames(120, '2h-sword');
  const oneHand = whirlwindFrames(120, '1h');
  assert.equal(sword.interpolated, true);
  assert.equal(oneHand.interpolated, true);
  assert.ok(Math.abs(sword.frames - 12) < 1e-9);
  assert.ok(Math.abs(oneHand.frames - 10.5) < 1e-9);
});

test('Whirlwind Fury and Lucky Hit scale with the tick rate', () => {
  const fury = whirlwindFury({ attackSpeedPct: 120 });
  assert.ok(Math.abs(fury.ticksPerSecond - 60 / 13) < 1e-9);
  assert.ok(Math.abs(fury.costPerSecond - 15 * ((60 / 13) / (30 / 13))) < 1e-9);
  const flat = whirlwindFury({ attackSpeedPct: 120, whirlwindAttackSpeedModel: 'flat' });
  assert.ok(Math.abs(flat.costPerSecond - 15) < 1e-9);
  const ticks = 60 / 13;
  assert.ok(Math.abs(whirlwindEffectPerSecond({ kind: 'lucky-hit', perTick: 2 }, ticks) - 2 * ticks) < 1e-9);
  assert.ok(Math.abs(whirlwindEffectPerSecond({ kind: 'on-hit', perTick: 4 }, ticks) - 4 * ticks) < 1e-9);
  assert.equal(whirlwindEffectPerSecond({ kind: 'dust-devil', perSecond: 5 }, ticks), 5);
  assert.equal(whirlwindEffectPerSecond({ kind: 'flat-dot', perSecond: 7 }, ticks), 7);
  const catalog = read('../data/barbarian.json');
  const build = read('../data/builds.json').builds.find(item => item.id === 'users-current-build');
  const table = whirlwindBreakpointTable(catalog, build);
  assert.deepEqual(table.map(row => row.attackSpeedPct), [0, 27.5, 48.8, 91, 143.5]);
  assert.equal(table.filter(row => row.defaultLanding).length, 1);
  assert.equal(table.find(row => row.defaultLanding).frames, 13);
  const above = table.find(row => row.attackSpeedPct === 143.5);
  assert.equal(above.aboveCap, true);
  assert.equal(above.referenceOnly, true);
  assert.equal(above.frames, 10);
});

test('attack speed above the 120% cap is worth 0', () => {
  const capped = whirlwindFury({ attackSpeedPct: 143.5 });
  const atCap = whirlwindFury({ attackSpeedPct: 120 });
  assert.equal(capped.frames, atCap.frames);
  assert.equal(capped.cap, 120);
  assert.ok(Math.abs(capped.ticksPerSecond - atCap.ticksPerSecond) < 1e-9);
  const catalog = read('../data/barbarian.json');
  const build = read('../data/builds.json').builds.find(item => item.id === 'users-current-build');
  const over = attackSpeedOverCap(catalog, build);
  assert.equal(over.cap, 120);
  assert.equal(over.label, 'user-observed in-game, S15; recheck S16');
  assert.ok(Math.abs(over.overCap - 151.5) < 1e-9);
  assert.equal(over.wasted.length, 4);
  const moved = reallocateOverCapAttackSpeed(catalog, build);
  for (const row of moved.report.replacements) {
    assert.equal(row.worth, 0);
    assert.equal(moved.build.gear.some(slot => (slot.affixes || []).some(affix => affix.affixId === row.affixId)), false);
  }
  const weapon = moved.build.gear.find(slot => slot.slotId === 'weapon-1');
  const spirit = moved.build.gear.find(slot => slot.slotId === 'weapon-3');
  assert.equal(weapon.affixes.some(affix => affix.affixId === 'v1-insight-damage'), true);
  assert.equal(spirit.affixes.some(affix => affix.affixId === 'v1-spirit-all-damage'), true);
  const ww = scoreS16(catalog, build).find(row => row.id === 's16-whirlwind');
  assert.equal(ww.whirlwind.weaponId, '2h-polearm');
  assert.equal(ww.whirlwind.framesEstimate, true);
  assert.equal(ww.mightTwoHander.count, 1);
  assert.equal(ww.lines.some(line => line.name === 'Polearm Expertise'), true);
  assert.equal(ww.lines.some(line => line.name === 'Might, two-handed damage'), false);
});
